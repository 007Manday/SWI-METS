HEAD = '''import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(CONTENT)))
from src_helpers import hazards_from
from swi_common import *
NUM = '%s'
TITLE = %r
NEW_TITLE = TITLE
NEW_JSEA = 'JSEA-PRO-MET-' + NUM
HAZARDS = hazards_from(os.environ['SRC_DOCX'])
'''
def write(num, title, d):
    s = HEAD % ('206-' + num, title)
    s += 'PPE = %s\n' % d.get('ppe', 'PPE_LAB_ACID')
    sc = d['sc']
    s += 'DESC = desc206(%r, %r, NUM, %r, extra_bold=%r)\n' % (d['desc'], d['freq'], sc, d.get('bold', []))
    pre = ('[LAB_ALONE] + ' if sc else '') + repr(d.get('pre', []))
    steps = ["    ('Pre-start Check', PRESTART_LAB_HAZ, prestart_lab(NEW_JSEA, %s), None, %r + [PPE_EQ])," % (pre, d['equip'])]
    for t, hz, bl, cau in d['steps']:
        steps.append('    (%r, %r, %r, %r, None),' % (t, hz, bl, cau))
    steps.append('    CLOSE_LAB_STEP,')
    s += 'STEPS = [\n' + '\n'.join(steps) + '\n]\n'
    s += 'REFS = refs206(NUM, TITLE, %r)\n' % d['refs']
    s += 'EMERG = emerg(%s, %r)\n' % (d['emerg'], d.get('eqp', 'bench equipment'))
    open('content_206_%s.py' % num, 'w').write(s)

